#!/usr/bin/env python3
"""Copy gl44's source tree and build_gl44's own scripts from the container to the project folder's mgs2/main/ (2026-11-28).
Adapted from tools/mirror43.py: tree t44 (not gen41/, no generated headers), main's tools/scripts/cfg, and build_gl44's
scripts into attic/gl44/scripts/ (as attic/gl43/scripts/ holds gl43's). Writes a manifest (md5, copied|same, dst path).
DRY=1 lists without copying."""
import os, sys, shutil, hashlib, fnmatch
DST = '/mnt/project-files/mgs2/main'
MAN = sys.argv[1]
DRY = os.environ.get('DRY') == '1'
out = []
left = []
def cp(src, rel):
    dst = os.path.join(DST, rel)
    data = open(src, 'rb').read()
    if b'\0' in data[:1 << 20]:
        left.append('binary: ' + src); return
    h = hashlib.md5(data).hexdigest()
    if os.path.exists(dst) and open(dst, 'rb').read() == data:
        out.append((rel, h, 'same')); return
    if not DRY:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst); shutil.copystat(src, dst)
    out.append((rel, h, 'copied' if not DRY else 'would copy'))
def generated(p):
    head = open(p, 'rb').read(400).lower()
    return b'generated by' in head or b'auto-generated' in head
# A. gl44's final tree (not gen41/: generated from the game's VU code; no generated headers)
T = '/home/claude/t44'
for root, dirs, files in os.walk(T):
    dirs[:] = sorted(d for d in dirs if d not in ('gen41', '__pycache__'))
    for f in sorted(files):
        p = os.path.join(root, f)
        if generated(p):
            left.append('generated: ' + p); continue
        cp(p, os.path.relpath(p, T))
# B. the main folder's tools, scripts, cfg
M = '/home/claude/main'
for d in ('tools', 'scripts', 'cfg'):
    for root, dirs, files in os.walk(os.path.join(M, d)):
        dirs[:] = sorted(x for x in dirs if x != '__pycache__')
        for f in sorted(files):
            p = os.path.join(root, f)
            if os.path.getsize(p) < 1 << 20 and not f.endswith(('.pyc', '.o')):
                cp(p, os.path.relpath(p, M))
# C. build_gl44's own scripts -> attic/gl44/scripts/
EXT = ('.sh', '.py', '.cfg', '.diff', '.md', '.ld')
B = os.path.join(M, 'build_gl44')
for f in sorted(os.listdir(B)):
    p = os.path.join(B, f)
    if os.path.isfile(p) and f.endswith(EXT) and os.path.getsize(p) < 300000:
        cp(p, 'attic/gl44/scripts/%s' % f)
for sub in ('tools', 'cfg', 'cfg_emu', 'rd', 'padld'):
    S = os.path.join(B, sub)
    for root, dirs, files in os.walk(S):
        dirs[:] = sorted(x for x in dirs if x != '__pycache__')
        for f in sorted(files):
            p = os.path.join(root, f)
            if os.path.getsize(p) < 300000 and not f.endswith(('.pyc', '.o', '.bin', '.out')) and not fnmatch.fnmatch(f, 'gen_*'):
                cp(p, 'attic/gl44/scripts/' + os.path.relpath(p, B))
with open(MAN, 'w') as f:
    for rel, h, st in out:
        f.write('%s  %s  %s\n' % (h, st, rel))
for l in left:
    print('  left: ' + l)
print('files', len(out), 'copied', sum(1 for o in out if o[2] != 'same'), 'same', sum(1 for o in out if o[2] == 'same'))
