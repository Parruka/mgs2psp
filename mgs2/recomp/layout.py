"""layout.py <elf> <prof> [out=demo_src/hot_order.h]: hot-code layout from an emulator profile (psp_game/emu_prof.sh: per-PC counts and the
call edges <prof>.calls).  The functions that run in the profile window are clustered by their call edges (C3: Ottoni & Maher 2017: a
function joins the cluster of its most frequent caller while the cluster stays small enough to share the instruction cache, then
clusters by density), and each gets a section .text.sorted.NNNNN (the default PSP link script places SORT(.text.sorted.*) first, in
name order), declared by prototypes in hot_order.h, included at the top of main.c.  The I-cache is 16 KB 2-way: a hot loop whose code is
contiguous and below 16 KB cannot evict itself."""
import sys, subprocess, bisect, re, os
elf, prof = sys.argv[1], sys.argv[2]
out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'demo_src', 'hot_order.h')
LIMIT = int(os.environ.get('LAYOUT_CLUSTER', '12288'))
# groups placed first, in this order (known hot loops whose calls the profile cannot see: tail calls, function-pointer tables): the skeleton
# loop of ComputeSkeletalHierarchy (per bone: the sampler through the bone table, SampleQuaternionStream, the VU0 program)
SEED = os.environ.get('LAYOUT_SEED', 'P19e1b0,JALR,P1a6590,P1a64b0,P1a6300,P1a0240,P1a6150,P1a0d70,vu_run,vucf_dispatch,vucf_82a952bf_e93,vucf_82a952bf_e175,mx_mul').split(',')
syms = []
for ln in subprocess.run(['/home/claude/pspsdk/pspdev/bin/psp-nm', '-n', '-S', elf], capture_output=True, text=True).stdout.split('\n'):
    p = ln.split()
    if len(p) == 4 and p[2] in 'tT': syms.append((int(p[0], 16), int(p[1], 16), p[3]))
addrs = [a for a, s, n in syms]
def fn_of(pc):
    i = bisect.bisect_right(addrs, pc) - 1
    return syms[i][2] if i >= 0 and pc < syms[i][0] + syms[i][1] else None
size = {n: s for a, s, n in syms}
cost = {}
for ln in open(prof):
    if ln.startswith('#'): continue
    pc, c, im, dm = ln.split(); f = fn_of(int(pc, 16))
    if f: cost[f] = cost.get(f, 0) + int(c) + 64 * int(im)
edges = {}
for ln in open(prof + '.calls'):
    a, b, n = ln.split(); fa, fb = fn_of(int(a, 16)), fn_of(int(b, 16))
    if fa and fb and fa != fb: edges[(fa, fb)] = edges.get((fa, fb), 0) + int(n)
base = lambda n: re.sub(r'\.(constprop|isra|part|cold)\.\d+$', '', n)
# C3 clustering
order = sorted(cost, key=lambda f: -cost[f]); clus = {f: [f] for f in order}; of = {f: f for f in order}
csize = lambda c: sum(size.get(f, 0) for f in clus[c])
callers = {}
for (a, b), n in edges.items(): callers.setdefault(b, []).append((n, a))
for f in order:
    cs = sorted(callers.get(f, []), reverse=True)
    if not cs: continue
    n, c = cs[0]
    if c not in of: continue
    A, B = of[c], of[f]
    if A == B or csize(A) + csize(B) > LIMIT: continue
    clus[A] += clus[B]
    for g in clus[B]: of[g] = A
    del clus[B]
dens = lambda c: sum(cost.get(f, 0) for f in clus[c]) / max(1, csize(c))
seq = SEED + [f for c in sorted(clus, key=lambda c: -dens(c)) for f in clus[c] if base(f) not in SEED]
# the prototypes need the function types: recompiled P / O / X_ functions are void(void); the micro-program forms int(int); a few host
# functions by their declarations; anything else keeps its place
SIG = {'vu_run': 'static void vu_run(int pc)', 'JALR': 'static void JALR(uint32_t t)', 'vu_aot_': 'static int vu_aot_(uint32_t h, int pc)',
       'vucf_dispatch': 'static int vucf_dispatch(uint32_t hash, int pc)', 'mx_mul': 'static void mx_mul(uint32_t o, uint32_t a, uint32_t b)'}
def proto(n):
    b = base(n)
    if b != n and b in done: return None
    if re.fullmatch(r'[PO][0-9a-f]{6}(_body)?|X_[0-9a-f]{6}', b): return 'static void %s(void)' % b
    if re.fullmatch(r'vuc[fv]?_[0-9a-f]{8}(_e\d+)?', b): return 'static int %s(int pc)' % b
    return SIG.get(b)
done = set(); lines = []; k = 0; tot = 0
for f in seq:
    p = proto(f)
    if not p: continue
    b = base(f)
    if b in done: continue
    done.add(b); lines.append('%s __attribute__((section(".text.sorted.%05d")));' % (p, k)); k += 1; tot += size.get(f, 0)
open(out, 'w').write('/* generated by model/layout.py from an emulator profile: the hot functions in cluster order (see there) */\n#ifndef HOT_ORDER_H\n#define HOT_ORDER_H\n#include <stdint.h>\n' + '\n'.join(lines) + '\n#endif\n')
print('%d functions placed (%d KB), %d clusters' % (k, tot // 1024, len(clus)))
